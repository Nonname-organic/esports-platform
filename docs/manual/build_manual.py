def main() -> None:
    out_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(out_dir, "AXELIA_操作マニュアル.pdf")
    tmp_path = os.path.join(out_dir, "_pass1.pdf")

    # ── 1パス目: 目次項目と本文ページ数を測る ────────────────────────────
    probe = Doc(tmp_path, DOC_TITLE, header_title=f"AXELIA {DOC_TITLE}")
    probe.enable_chrome()
    build(probe, toc_offset=0)
    probe.save()
    entries = probe.toc_entries
    body_pages = probe.page

    # 目次に必要なページ数（1ページあたりおよそ32行）
    toc_pages = max(1, math.ceil(len(entries) / 32))
    offset = 1 + toc_pages  # 表紙 + 目次

    shifted = [
        TocEntry(e.number, e.title, e.page + offset, e.level) for e in entries
    ]
    total = body_pages + offset

    # ── 2パス目: 本番 ────────────────────────────────────────────────────
    doc = Doc(out_path, DOC_TITLE, header_title=f"AXELIA {DOC_TITLE}")
    doc._total_pages = total
    doc.title_page(
        product="AXELIA",
        tagline="VALORANT 大会プラットフォーム",
        description=(
            "コミュニティ大会の募集掲載から、参加申請・抽選・対戦表の作成・"
            "試合結果の記録・戦績の蓄積までを一元管理するサービスです。"
        ),
        version=VERSION,
        date=DATE,
        contact=CONTACT,
    )
    doc.enable_chrome()
    doc.render_toc(shifted)
    doc.new_page()
    doc.toc_entries = []
    build(doc, toc_offset=offset)
    doc.save()

    if os.path.exists(tmp_path):
        os.remove(tmp_path)
    print(f"生成: {out_path}")
    print(f"  ページ数: {doc.page} / 目次項目: {len(entries)}")


if __name__ == "__main__":
    main()
